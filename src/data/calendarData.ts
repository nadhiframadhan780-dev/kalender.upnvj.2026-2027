// Helper to generate iCalendar (.ics) content
export function generateICalFile(): string {
  let ics = [
    'BEGIN:VCALENDAR',
    'VERSION:2.0',
    'PRODID:-//UPN Veteran Jakarta//Kalender Akademik 2026/2027//ID',
    'CALSCALE:GREGORIAN',
    'METHOD:PUBLISH',
    'X-WR-CALNAME:Kalender Akademik UPNVJ 2026/2027',
    'X-WR-TIMEZONE:Asia/Jakarta',
  ];

  ALL_EVENTS.forEach(evt => {
    // Format YYYYMMDD
    const startStr = evt.startDate.replace(/-/g, '');
    // End date in ics for full day event should be +1 day or same day
    const [y, m, d] = evt.endDate.split('-').map(Number);
    const endDateObj = new Date(Date.UTC(y, m - 1, d + 1));
    const endStr = `${endDateObj.getUTCFullYear()}${String(endDateObj.getUTCMonth() + 1).padStart(2, '0')}${String(endDateObj.getUTCDate()).padStart(2, '0')}`;

    ics.push(
      'BEGIN:VEVENT',
      `UID:${evt.id}-20262027@upnvj.ac.id`,
      `DTSTAMP:${new Date().toISOString().replace(/[-:.]/g, '').slice(0, 15)}Z`,
      `DTSTART;VALUE=DATE:${startStr}`,
      `DTEND;VALUE=DATE:${endStr}`,
      `SUMMARY:${evt.title}`,
      `DESCRIPTION:${evt.description} (Kalender Akademik UPNVJ 2026/2027)`,
      'LOCATION:UPN "Veteran" Jakarta, Jl. RS Fatmawati No. 1 Pondok Labu, Jakarta Selatan',
      'STATUS:CONFIRMED',
      'TRANSP:TRANSPARENT',
      'END:VEVENT'
    );
  });

  ics.push('END:VCALENDAR');
  return ics.join('\r\n');
}
